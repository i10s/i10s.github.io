#!/usr/bin/env node

/**
 * CSP hashes: lists the SHA-256 of every inline <script> in the published HTML, so the Worker's
 * Content-Security-Policy can allow exactly those scripts instead of 'unsafe-inline'
 * (worker/src/site.js imports worker/src/csp-hashes.js).
 *
 * Usage:
 *   npm run generate:csp                  # rewrite worker/src/csp-hashes.js
 *   node scripts/csp-hashes.js --check    # exit 1 if it is stale
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const root = path.join(__dirname, '..');
const output = path.join(root, 'worker', 'src', 'csp-hashes.js');

// Script types the browser executes (and CSP governs); data blocks such as JSON-LD are not scripts.
const EXECUTABLE = new Set(['', 'text/javascript', 'application/javascript', 'module', 'speculationrules', 'importmap']);

// Top-level entries of .assetsignore are not published, so their HTML does not need hashes.
function unpublished() {
  return fs.readFileSync(path.join(root, '.assetsignore'), 'utf8')
    .split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'));
}

function publishedHtml() {
  const ignored = unpublished();
  return execFileSync('git', ['ls-files', '*.html'], { cwd: root, encoding: 'utf8' })
    .split('\n').filter(Boolean)
    .filter(file => !ignored.some(entry => file === entry || file.startsWith(`${entry}/`)));
}

function inlineScripts(html) {
  const scripts = [];
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    if (/\bsrc\s*=/i.test(attrs) || !body) continue;
    const type = ((attrs.match(/\btype\s*=\s*["']?([^"'\s>]+)/i) || [])[1] || '').toLowerCase();
    if (EXECUTABLE.has(type)) scripts.push(body);
  }
  return scripts;
}

const digest = body => `'sha256-${crypto.createHash('sha256').update(body, 'utf8').digest('base64')}'`;

function build() {
  const hashes = new Set();
  publishedHtml().forEach(file => inlineScripts(fs.readFileSync(path.join(root, file), 'utf8')).forEach(body => hashes.add(digest(body))));
  return `// Generated by scripts/csp-hashes.js (npm run generate:csp); do not edit by hand.\nexport const SCRIPT_HASHES = ${JSON.stringify([...hashes].sort(), null, 2)};\n`;
}

if (require.main === module) {
  const content = build();
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (content !== current) {
      console.error('worker/src/csp-hashes.js is stale: run npm run generate:csp');
      process.exit(1);
    }
    console.log('CSP hashes up to date.');
  } else {
    fs.writeFileSync(output, content);
    console.log(`Wrote ${path.relative(root, output)} (${(content.match(/'sha256-/g) || []).length} inline scripts).`);
  }
}

module.exports = { build, inlineScripts, digest };
