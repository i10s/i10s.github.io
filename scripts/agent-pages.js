function aboutPage(home, now) {
  const url = `${SITE}/about.html`;
  const description = `About ${NAME}, technology executive and entrepreneur in Palma de Mallorca. ${home.querySelector('meta[name="description"]').getAttribute('content')}`;
  const bio = Array.from(home.querySelectorAll('#bio ~ p')).map(p => `    <p>${p.innerHTML.trim()}</p>`).join('\n');
  const current = Array.from(now.querySelectorAll('.card')).map(card =>
    `      <li><p class="k">${esc(clean(card.querySelector('header > span').textContent))}</p><p><strong>${esc(clean(card.querySelector('h3').textContent))}</strong>: ${card.querySelector('p').innerHTML.trim()}</p></li>`).join('\n');
  const track = Array.from(home.querySelectorAll('[aria-labelledby="arr"] .rows li')).map(li => {
    const [time, origin, flight, , remarks] = Array.from(li.querySelectorAll(':scope > span')).map(s => clean(s.textContent));
    return `      <li><p class="k">${esc(time)}</p><p>${esc(flight)}, ${esc(origin)}${/^acquired/i.test(remarks) ? ` · ${esc(remarks)}` : ''}</p></li>`;
  }).join('\n');
  const body = `  <section aria-labelledby="short">
    <h2 id="short">In short</h2>
${bio}
  </section>

  <section aria-labelledby="current">
    <h2 id="current">Right now</h2>
    <ul class="rows">
${current}
    </ul>
    <p>More on the <a href="/now.html">Now page</a>.</p>
  </section>

  <section aria-labelledby="track">
    <h2 id="track">Track record</h2>
    <ul class="rows">
${track}
    </ul>
    <p>Dates, education, certifications and awards in the <a href="/resume.html">résumé</a>.</p>
  </section>

  <section aria-labelledby="more">
    <h2 id="more">Elsewhere</h2>
    <p>Long-form writing on the <a href="/blog/">blog</a> (in Spanish). To get in touch, see the <a href="/contact.html">contact page</a>.</p>
  </section>`;
  const ld = { '@context': 'https://schema.org', '@type': 'AboutPage', '@id': url, url, name: `About · ${NAME}`, description, inLanguage: 'en',
    isPartOf: { '@id': `${SITE}/#website` }, about: { '@id': `${SITE}/#person` }, mainEntity: PERSON, breadcrumb: crumbs('About', url) };
  return page({ title: `About · ${NAME}`, description, canonical: url, eyebrow: 'About · Palma de Mallorca', heading: `About ${NAME}`, word: 'ABOUT',
    lede: esc(clean(home.querySelector('.lede').textContent)) + ' ' + esc(clean(home.querySelector('.sign').textContent)), body, ld });
}

