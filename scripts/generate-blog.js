// ── Markdown (the subset posts use) ───────────────────────────────────────────────────────────────
function inline(text) {
  const codes = [];
  let s = esc(text).replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, href) => {
    const url = href.replace(/&amp;/g, '&');
    if (!/^(https?:\/\/|\/|#|mailto:)/.test(url)) throw new Error(`unsupported link target: ${url}`);
    return `<a href="${esc(url)}">${label}</a>`;
  });
  s = s.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>').replace(/(^|[^*\w])\*([^*\n]+)\*(?!\w)/g, '$1<em>$2</em>')
    .replace(/(^|[^_\w])_([^_\n]+)_(?!\w)/g, '$1<em>$2</em>');
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${codes[Number(i)]}</code>`);
}

function markdown(src) {
  const lines = src.replace(/\r\n/g, '\n').split('\n');
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    if (line.startsWith('```')) {
      const body = [];
      for (i++; i < lines.length && !lines[i].startsWith('```'); i++) body.push(lines[i]);
      i++;
      out.push(`<pre><code>${esc(body.join('\n'))}</code></pre>`);
      continue;
    }
    const h = line.match(/^(#{2,3})\s+(.+)$/);
    if (h) { out.push(`<h${h[1].length}>${inline(h[2].trim())}</h${h[1].length}>`); i++; continue; }
    if (/^#\s/.test(line)) throw new Error('use ## and ### in posts; the title is the only h1');
    if (line.startsWith('>')) {
      const q = [];
      for (; i < lines.length && lines[i].startsWith('>'); i++) q.push(lines[i].replace(/^>\s?/, ''));
      out.push(`<blockquote>${markdown(q.join('\n'))}</blockquote>`);
      continue;
    }
    const list = line.match(/^(\s*)([-*]|\d+\.)\s+/);
    if (list) {
      const ordered = /\d/.test(list[2]);
      const items = [];
      for (; i < lines.length && /^\s*([-*]|\d+\.)\s+/.test(lines[i]); i++) items.push(lines[i].replace(/^\s*([-*]|\d+\.)\s+/, ''));
      const tag = ordered ? 'ol' : 'ul';
      out.push(`<${tag}>${items.map(it => `<li>${inline(it)}</li>`).join('')}</${tag}>`);
      continue;
    }
    const para = [];
    for (; i < lines.length && lines[i].trim() && !/^(#{2,3}\s|>|```|\s*([-*]|\d+\.)\s+)/.test(lines[i]); i++) para.push(lines[i].trim());
    out.push(`<p>${inline(para.join(' '))}</p>`);
  }
  return out.join('\n');
}

// ── posts ─────────────────────────────────────────────────────────────────────────────────────────
function readPosts() {
  if (!fs.existsSync(POSTS_DIR)) return [];
  const posts = fs.readdirSync(POSTS_DIR).filter(f => f.endsWith('.md')).sort().map(file => {
    const raw = fs.readFileSync(path.join(POSTS_DIR, file), 'utf8');
    const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!m) throw new Error(`${file}: missing front matter`);
    const meta = {};
    m[1].split('\n').forEach(l => {
      const kv = l.match(/^([a-z_]+):\s*(.*)$/);
      if (kv) meta[kv[1]] = kv[2].replace(/\s+#.*$/, '').trim().replace(/^["']|["']$/g, '');
    });
    const fm = file.match(/^(\d{4}-\d{2}-\d{2})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/);
    if (!fm) throw new Error(`${file}: name must be YYYY-MM-DD-slug.md (lowercase ascii slug)`);
    const slug = fm[2];
    const date = parseDate(meta.date || fm[1]);
    const updated = meta.updated ? parseDate(meta.updated) : date;
    const errors = [];
    if (!meta.title) errors.push('title');
    if (!meta.description || meta.description.length > 200) errors.push('description (1–200 chars)');
    if (!TOPICS[meta.topic]) errors.push(`topic (${Object.keys(TOPICS).join(' | ')})`);
    if (!date) errors.push('date (YYYY-MM-DD)');
    if (!updated) errors.push('updated (YYYY-MM-DD)');
    if (['posts', 'tema', 'feed', 'index'].includes(slug)) errors.push('slug (reserved)');
    if (errors.length) throw new Error(`${file}: invalid ${errors.join(', ')}`);
    const body = m[2].trim();
    const words = body.split(/\s+/).filter(Boolean).length;
    return { file, slug, date, updated, meta, body, html: markdown(body), lang: meta.lang || 'es',
      minutes: Math.max(1, Math.round(words / 220)), url: `${SITE}/blog/${slug}/` };
  });
  const seen = new Set();
  posts.forEach(p => {
    if (seen.has(p.slug)) throw new Error(`duplicate slug: ${p.slug}`);
    seen.add(p.slug);
  });
  return posts.sort((a, b) => b.date - a.date || a.slug.localeCompare(b.slug));
}

