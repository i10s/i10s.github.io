/**
 * Blog generator. blog/posts/*.md (front matter + Markdown) are the only source; everything else is
 * derived from them, so nothing can drift:
 *
 *   blog/index.html                  all posts, newest first (departures-board list)
 *   blog/tema/<topic>/index.html     posts by topic
 *   blog/<slug>/index.html           each post (clean URL https://ifuentes.net/blog/<slug>/)
 *   blog/<slug>.md                   Markdown version for agents (rel="alternate" type="text/markdown")
 *   blog/feed.xml                    RSS 2.0 with full content
 *   sitemap.xml                      the block between <!-- blog:start --> and <!-- blog:end -->
 *
 * Post file: blog/posts/YYYY-MM-DD-slug.md
 *   ---
 *   title: Los datos son el input
 *   date: 2026-10-23
 *   description: One or two sentences for search results and social cards (max 200 chars).
 *   topic: evoost            # personal | liderazgo | tecnologia | evoost | fliinow
 *   lang: es                 # optional, default es
 *   updated: 2026-11-02      # optional
 *   ---
 *   Markdown body: paragraphs, ## and ### headings, - and 1. lists, > quotes, ``` code,
 *   **bold**, *italic*, `code` and [links](https://…).
 *
 * Usage:
 *   npm run generate:blog                     # write files
 *   node scripts/generate-blog.js --check     # exit 1 if any generated file is out of date
 */

